let lang = store.get('lang') ?? 'pl';

export const getLang = () => lang;

export function setLang(next) {
  lang = STRINGS[next] ? next : 'pl';
  store.set('lang', lang);
  document.documentElement.lang = lang;
}

export function t(key, params = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.pl[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, p) => params[p] ?? '');
}

export function applyI18n(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-label]')) node.setAttribute('aria-label', t(node.dataset.i18nLabel));
}
